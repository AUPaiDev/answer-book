    // 加权非放回随机抽样辅助函数
    function weightedSampleWithoutReplacement(items, weights, count) {
        const pool = items.map((item, idx) => ({ item, weight: Math.max(0.01, weights[idx]) }));
        const result = [];
        while (result.length < count && pool.length > 0) {
            const totalWeight = pool.reduce((acc, curr) => acc + curr.weight, 0);
            let randomVal = Math.random() * totalWeight;
            let selectedIdx = 0;
            for (let i = 0; i < pool.length; i++) {
                randomVal -= pool[i].weight;
                if (randomVal <= 0) {
                    selectedIdx = i;
                    break;
                }
            }
            result.push(pool[selectedIdx].item);
            pool.splice(selectedIdx, 1);
        }
        return result;
    }

    // 相对随机性翻书抽样引擎（加权共鸣 + 逆向破局 + 全书盲选 + 连抽降权去重）
    function findRelevantPages(question, topN = 18, excludePages = []) {
        if (!BOOK_PAGES || BOOK_PAGES.length === 0) return [];
        const coolDownSet = new Set(Array.isArray(excludePages) ? excludePages : []);

        if (!question || typeof question !== 'string') {
            const pool = BOOK_PAGES.filter(p => !coolDownSet.has(p.page));
            const shuffled = (pool.length >= topN ? pool : BOOK_PAGES).sort(() => Math.random() - 0.5);
            return shuffled.slice(0, topN);
        }

        const q = question.toLowerCase();
        
        // 1. 识别主题与共鸣标签
        const activeThemes = new Set();
        const relevantTags = new Set();
        for (const [theme, cfg] of Object.entries(THEME_CONFIG)) {
            for (const kw of cfg.keywords) {
                if (q.includes(kw)) {
                    activeThemes.add(theme);
                    (cfg.tags || []).forEach(t => relevantTags.add(t));
                    break;
                }
            }
        }

        // 2. 提取双字词特征
        const cleanQ = q.replace(/[\s\p{P}+~$`^=|<>～—_+]/gu, '');
        const qBigrams = [];
        for (let i = 0; i < cleanQ.length - 1; i++) {
            qBigrams.push(cleanQ.slice(i, i + 2));
        }

        // 3. 计算意向基础分与加权概率（对刚抽过的页码施加冷却惩罚）
        const scored = BOOK_PAGES.map(item => {
            let score = 0;
            if (item.tags) {
                for (const tag of item.tags) {
                    if (relevantTags.has(tag)) score += 4;
                    if (q.includes(tag)) score += 3;
                }
            }
            for (const bi of qBigrams) {
                if (item.oracle.includes(bi)) score += 2;
            }
            // 加权基底
            let weight = Math.pow(score + 1, 1.2);
            if (coolDownSet.has(item.page)) {
                weight *= 0.05; // 刚翻过的书页降权20倍，避免连续翻开同一页
            }
            return { item, weight, score };
        });

        const selectedPages = new Set();
        const result = [];

        // 4. 第一层抽样：意图共鸣候选池（加权概率抽样 5~6 页，消除顶部分数绝对霸榜）
        const resonantPool = scored.filter(s => s.score > 0);
        const resonantQuota = Math.max(5, Math.floor(topN * 0.35));
        const resonantSampled = weightedSampleWithoutReplacement(
            resonantPool.map(p => p.item),
            resonantPool.map(p => p.weight),
            resonantQuota
        );

        for (const item of resonantSampled) {
            selectedPages.add(item.page);
            result.push(item);
        }

        // 5. 第二层抽样：逆向反思/警醒棒喝候选池（打破定势思维，抽样 5~6 页）
        const contrarianCandidates = BOOK_PAGES.filter(p =>
            !selectedPages.has(p.page) && (p.tags || []).some(t => CONTRARIAN_TAGS.has(t))
        ).sort(() => Math.random() - 0.5);

        const contrarianQuota = Math.max(5, Math.floor(topN * 0.35));
        for (const p of contrarianCandidates) {
            if (result.length >= resonantQuota + contrarianQuota) break;
            selectedPages.add(p.page);
            result.push(p);
        }

        // 6. 第三层抽样：全书物理翻阅盲选（模拟随手翻开书页的机缘巧合）
        const remainingCandidates = BOOK_PAGES.filter(p => !selectedPages.has(p.page))
            .sort(() => Math.random() - 0.5);

        for (const p of remainingCandidates) {
            if (result.length >= topN) break;
            selectedPages.add(p.page);
            result.push(p);
        }

        // 7. Fisher-Yates 彻底打乱候选次序，消除位置倾向偏见
        for (let i = result.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [result[i], result[j]] = [result[j], result[i]];
        }

        return result;
    }

    // 严防实体泄露审查器：确保神谕文本绝对不包含提问中的特定名词、人名或具体事物
    function sanitizeOracle(rawOracle, rawPage, question, candidatePages) {
        const defaultCandidate = (candidatePages && candidatePages.length > 0) ? candidatePages[0] : BOOK_PAGES[0];
        let finalOracle = rawOracle ? String(rawOracle).trim() : defaultCandidate.oracle;
        let finalPage = parseInt(rawPage, 10);
        if (isNaN(finalPage) || finalPage < 1 || finalPage > 365) {
            const matched = BOOK_PAGES.find(p => p.oracle === finalOracle);
            finalPage = matched ? matched.page : defaultCandidate.page;
        }

        const cleanQ = (question || '').replace(/[\s\p{P}+~$`^=|<>～—_+]/gu, '');
        const stopWords = ['我们','你们','他们','这个','那个','怎么','怎样','如何','为什么','要不要','该不该','是不是','能不能','会不会','可以吗','什么','请问','如果','但是','现在','今天','明天','以后','请问','告诉我','到底','想知道'];

        for (let len = 2; len <= Math.min(cleanQ.length, 6); len++) {
            for (let i = 0; i <= cleanQ.length - len; i++) {
                const sub = cleanQ.slice(i, i + len);
                if (!stopWords.includes(sub) && finalOracle.includes(sub)) {
                    return { page: defaultCandidate.page, oracle: defaultCandidate.oracle };
                }
            }
        }
        return { page: finalPage, oracle: finalOracle };
    }

    // 严控解读字数，避免超出书页显示极限（90 ~ 130字）
    function sanitizeReading(rawReading) {
        let reading = rawReading ? String(rawReading).trim() : "顺应内心的真实潮汐，答案自会在前路坦然浮现。";
        if (reading.length > 135) {
            const cut = reading.slice(0, 130);
            const lastPunc = Math.max(cut.lastIndexOf('。'), cut.lastIndexOf('！'), cut.lastIndexOf('？'));
            if (lastPunc > 70) {
                reading = cut.slice(0, lastPunc + 1);
            } else {
                reading = cut + '。';
            }
        }
        return reading;
    }

